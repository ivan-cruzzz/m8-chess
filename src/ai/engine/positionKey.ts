import type { Chess } from 'chess.js';

/**
 * Ключ позиции для транспозиционной таблицы: точная строка из первых четырёх
 * полей FEN (доска, сторона, права рокировки, взятие на проходе).
 * Поля полуходов/номера хода исключены — TT интересует идентичность позиции,
 * а не путь к ней. Инкрементальный Zobrist появится вместе с fastboard (этап 5):
 * публичный API chess.js не даёт доступа к внутреннему представлению доски.
 */
export function positionKey(game: Chess): string {
  return game.fen().split(' ').slice(0, 4).join(' ');
}
