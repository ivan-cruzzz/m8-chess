import { describe, it, expect } from 'vitest';
import { fill } from '../fill';

describe('fill: ручные подстановки в строках i18n', () => {
  it('заменяет одиночный плейсхолдер числом', () => {
    expect(fill('Пользователей: {n}', { n: 42 })).toBe('Пользователей: 42');
  });

  it('заменяет несколько разных плейсхолдеров', () => {
    expect(fill('{uses} из {max}', { uses: 1, max: 5 })).toBe('1 из 5');
  });

  it('подставляет строковые значения, а без совпадений возвращает строку как есть', () => {
    expect(fill('Сбросить прогресс {name}?', { name: 'Аня' })).toBe('Сбросить прогресс Аня?');
    expect(fill('Без подстановок', {})).toBe('Без подстановок');
  });
});
